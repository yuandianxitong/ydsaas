import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pluginsDir = join(root, 'server/plugins')
const pcPluginsDir = join(root, 'pc/plugins')
const generatedDir = join(root, 'pc/generated')

mkdirSync(pcPluginsDir, { recursive: true })
mkdirSync(generatedDir, { recursive: true })

const routes = []
const diyRenderers = []

for (const code of readdirSync(pluginsDir)) {
  const pluginDir = join(pluginsDir, code)
  const manifestPath = join(pluginDir, 'plugin.json')
  const pcDir = join(pluginDir, 'pc')
  if (!existsSync(manifestPath) || !existsSync(pcDir)) continue

  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const target = join(pcPluginsDir, code)
  rmSync(target, { recursive: true, force: true })
  cpSync(pcDir, target, { recursive: true })

  for (const page of manifest.pc?.pages || []) {
    if (!page.route || !page.component) continue
    routes.push({
      code: manifest.entitlement || manifest.code || code,
      pluginCode: manifest.code || code,
      route: page.route,
      title: page.title || '',
      component: page.component,
      auth: Boolean(page.auth),
      nav: Boolean(page.nav),
    })
  }

  // DIY 渲染器协议 v1：diy_widgets[].renderer.pc（裸组件名，约定目录 pc/components/diy/）
  for (const w of manifest.diy_widgets || []) {
    const name = w?.renderer?.pc
    if (!w?.type || typeof name !== 'string' || !/^[A-Za-z][A-Za-z0-9_-]*$/.test(name)) continue
    diyRenderers.push({
      type: w.type,
      component: `plugins/${manifest.code || code}/components/diy/${name}`,
    })
  }
}

const content = `// This file is generated by scripts/sync-plugin-pc.mjs
export const pluginRoutes = ${JSON.stringify(routes, null, 2)} as const
`

writeFileSync(join(generatedDir, 'plugin-routes.ts'), content)

const diyContent = `// This file is generated by scripts/sync-plugin-pc.mjs
// widget type → 插件 DIY 渲染器组件路径（相对 pc/，DiyPluginWidget 宿主经 import.meta.glob 解析）
export const diyRenderers = ${JSON.stringify(diyRenderers, null, 2)} as const
`

writeFileSync(join(generatedDir, 'diy-renderers.ts'), diyContent)
console.log(`[sync-plugin-pc] synced ${routes.length} route(s), ${diyRenderers.length} diy renderer(s)`)
